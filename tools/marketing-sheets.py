def insert_block(html, key, anchor_re, block):
    u"""แทรกบล็อกโดยคร่อมคอมเมนต์ · ถ้ามีอยู่แล้วให้แทนที่ของเดิม"""
    a, b = mark(key)
    if a in html and b in html:
        return re.sub(re.escape(a) + '.*?' + re.escape(b),
                      lambda _m: a + block + b, html, flags=re.S)
    m = re.search(anchor_re, html)
    if not m:
        raise SystemExit(u'หาจุดแทรกของ %s ไม่เจอ' % key)
    at = m.start()
    return html[:at] + a + block + b + '\n' + html[at:]


def build(html):
    # หัวข้อท้ายบท · แทรกก่อน </div> ที่ปิดแท็บของบทนั้น
    for key, nxt, block, num, label in SECTIONS:
        # จำนวนบรรทัดว่างระหว่างแท็บไม่เท่ากันทุกจุด จึงต้องยอมให้ยืดหยุ่น
        anchor = r'  </div>\n+  <div id="%s"' % nxt
        html = insert_block(html, 'sec-' + key, anchor, block)
        # รายการในแถบข้างซ้าย
        a, b = mark('rail-' + key)
        li = u'\n        <li><a href="#%s-%s"><i>%s</i>%s</a></li>\n      ' % (key, num, num, label)
        if a in html and b in html:
            html = re.sub(re.escape(a) + '.*?' + re.escape(b),
                          lambda _m: a + li + b, html, flags=re.S)
        else:
            nav = re.search(r'(<nav id="rail-%s"[^>]*>.*?)(</ol>)' % key, html, re.S)
            if not nav:
                raise SystemExit(u'หาแถบข้างของ %s ไม่เจอ' % key)
            html = html[:nav.end(1)] + a + li + b + html[nav.end(1):]

    # แบบฝึกหัดท้ายบท · ต่อท้ายคลังข้อสอบ
    # ตรงนี้อยู่ในบล็อกสคริปต์ จึงต้องคร่อมด้วยคอมเมนต์ของจาวาสคริปต์
    # ไม่ใช่คอมเมนต์ของ HTML ซึ่งเบราว์เซอร์ยอมรับก็จริงแต่เป็นของตกทอดที่ไม่ควรพึ่ง
    a, b = u'/* sheet:quiz:start */', u'/* sheet:quiz:end */'
    if a in html and b in html:
        html = re.sub(re.escape(a) + '.*?' + re.escape(b),
                      lambda _m: a + QUIZ + b, html, flags=re.S)
    else:
        m = re.search(r'(  var QS = \[.*?)(\n  \];)', html, re.S)
        if not m:
            raise SystemExit(u'หาคลังข้อสอบไม่เจอ')
        # ข้อสุดท้ายของเดิมไม่มีจุลภาคปิดท้าย ต้องเติมก่อน ไม่งั้นสคริปต์ทั้งหน้าพัง
        html = html[:m.end(1)] + ',\n' + a + QUIZ + b + html[m.end(1):]

    n = html.count('{ch:')
    html = html.replace(u'<p class="lede">79 ข้อ ครอบคลุมทั้งหกบท',
                        u'<p class="lede">%d ข้อ ครอบคลุมทั้งหกบท' % n)
    html = re.sub(r'0 จาก \d+ ข้อ', u'0 จาก %d ข้อ' % n, html)
    html = html.replace(u'<b>79 ข้อ</b>', u'<b>%d ข้อ</b>' % n)
    html = re.sub(r'(<a href="#quiz-top"><i>Q</i>)\d+( ข้อ</a>)', r'\g<1>%d\g<2>' % n, html)
    return html


def check_js(html):
    u"""ตรวจว่าสคริปต์ของหน้ายังคอมไพล์ได้

    เคยพลาดมาแล้วเพราะข้อสุดท้ายของคลังข้อสอบเดิมไม่มีจุลภาคปิดท้าย
    พอต่อข้อใหม่เข้าไปสคริปต์ทั้งหน้าก็พังเงียบ ๆ แท็บกดไม่ได้ทั้งหน้า
    """
    import shutil
    import subprocess
    import tempfile
    node = shutil.which('node') or '/opt/node22/bin/node'
    if not os.path.exists(node):
        print(u'  ไม่มี node ในเครื่อง ข้ามการตรวจไวยากรณ์สคริปต์')
        return 0
    m = re.search(r'<script>\n(\(function\(\).*?)\n</script>', html, re.S)
    if not m:
        print(u'  หาบล็อกสคริปต์ของหน้าไม่เจอ')
        return 1
    fd, path = tempfile.mkstemp(suffix='.js')
    try:
        with io.open(path, 'w', encoding='utf-8') as fh:
            fh.write(m.group(1))
        r = subprocess.run([node, '--check', path], capture_output=True, text=True)
    finally:
        os.close(fd)
        os.unlink(path)
    if r.returncode:
        print(u'  สคริปต์ของหน้าไวยากรณ์ผิด · %s'
              % (r.stderr.strip().splitlines() or [''])[-1][:100])
        return 1
    print(u'  สคริปต์ของหน้าคอมไพล์ผ่าน')
    return 0


def check(html):
    bad = check_js(html)
    for key, _nxt, _block, num, _label in SECTIONS:
        sid = '%s-%s' % (key, num)
        if 'id="%s"' % sid not in html:
            print(u'  ไม่พบหัวข้อ %s ในหน้า' % sid); bad += 1
        if 'href="#%s"' % sid not in html:
            print(u'  ไม่พบลิงก์ %s ในแถบข้าง' % sid); bad += 1
    n = html.count('{ch:')
    print(u'  คลังข้อสอบมี %d ข้อ' % n)
    if u'79 ข้อ' in html:
        print(u'  ยังมีข้อความ 79 ข้อ ค้างอยู่'); bad += 1
    # แท็กเปิดปิดของหัวข้อที่เพิ่ม ต้องสมดุล
    for key, _nxt, block, _num, _label in SECTIONS:
        if block.count('<section') != block.count('</section>'):
            print(u'  แท็ก section ของ %s ไม่สมดุล' % key); bad += 1
        if block.count('<div') != block.count('</div>'):
            print(u'  แท็ก div ของ %s ไม่สมดุล · เปิด %d ปิด %d'
                  % (key, block.count('<div'), block.count('</div>'))); bad += 1
        if block.count('<table') != block.count('</table>'):
            print(u'  แท็ก table ของ %s ไม่สมดุล' % key); bad += 1
    print(u'  ตรวจพบปัญหา %d จุด' % bad)
    return bad


def main():
    ap = argparse.ArgumentParser(description=u'เพิ่มเนื้อหาจากชีทอาจารย์ลงหน้าวิชาหลักการตลาด')
    ap.add_argument('--check', action='store_true', help=u'ตรวจอย่างเดียว ไม่เขียนไฟล์')
    a = ap.parse_args()

    html = io.open(PAGE, encoding='utf-8').read()
    if a.check:
        return 1 if check(html) else 0
    out = build(html)
    io.open(PAGE, 'w', encoding='utf-8').write(out)
    print(u'เพิ่มเนื้อหาจากชีทลง marketing/index.html แล้ว · โตขึ้น %.1f KB'
          % ((len(out) - len(html)) / 1024.0))
    return 1 if check(out) else 0


if __name__ == '__main__':
    sys.exit(main())
